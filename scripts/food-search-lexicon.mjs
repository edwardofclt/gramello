import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadOfflineFoods } from './food-catalog.mjs';
const normalize = text => text.normalize('NFKD').replace(/\p{M}/gu,'').toLowerCase().replace(/[^\p{L}\p{N}]+/gu,' ').trim().replace(/\s+/g,' ');

// Only catalog name/brand text enters this artifact; never queries, relevance
// judgments, nutrients or serving values. Stable sorting makes rebuilds auditable.
export function buildFoodSearchLexicon(foods) {
  const counts = new Map(), possessives = new Map(), genericWords = new Set();
  const source = foods.map(food=>[food.id,food.name,food.brand ?? '']).sort((a,b)=>a[0]<b[0]?-1:a[0]>b[0]?1:0);
  for (const [id,name,brand] of source) {
    if (id.startsWith('usda-')) for (const word of normalize(name).split(' ')) if (/^[a-z]{2,32}$/.test(word)) genericWords.add(word);
    for (const word of new Set(normalize(`${name} ${brand}`).split(' '))) {
      if (/^[a-z]{2,32}$/.test(word)) counts.set(word,(counts.get(word) ?? 0)+1);
    }
    for (const match of brand.matchAll(/([\p{L}]+)['’]s\b/gu)) {
      const root = normalize(match[1]);
      possessives.set(`${root}s`,`${root} s`);
    }
  }
  const knownWords = [...counts.keys()].sort();
  // Both singular and plural must be attested. Never strip an arbitrary terminal s.
  /** @type {Record<string, string>} */
  const plurals = {};
  for (const word of knownWords) {
    if (word.length < 5 || /(?:ss|us|is)$/.test(word)) continue;
    const candidates = word.endsWith('ies') ? [word.slice(0,-3)+'y']
      : /(?:ches|shes|xes|zes|oes)$/.test(word) ? [word.slice(0,-2),word.slice(0,-1)]
        : word.endsWith('s') ? [word.slice(0,-1)] : [];
    const found = candidates.filter(candidate=>counts.has(candidate));
    if (found.length === 1) plurals[word]=found[0];
  }
  return {
    version:1,sourceFoodCount:source.length,sourceTextSha256:createHash('sha256').update(JSON.stringify(source)).digest('hex'),
    knownWords,genericWords:[...genericWords].sort(),suggestionWords:knownWords.filter(word=>word.length>=5 && word.length<=24 && counts.get(word)>=2),
    possessives:Object.fromEntries([...possessives].sort(([a],[b])=>a<b?-1:a>b?1:0)),plurals,
  };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = resolve('lib/search/lexicon.generated.ts');
  const bytes = '// Generated by scripts/food-search-lexicon.mjs; do not edit.\nconst lexicon = '+JSON.stringify(buildFoodSearchLexicon(loadOfflineFoods()))+';\nexport default lexicon;\n';
  if (process.argv.includes('--check')) {
    if (readFileSync(target,'utf8') !== bytes) throw new Error('Food search lexicon is stale; run node scripts/food-search-lexicon.mjs');
    console.log('Food search lexicon matches source catalog text.');
  } else { writeFileSync(target,bytes); console.log(`Wrote ${target} (${Buffer.byteLength(bytes)} bytes)`); }
}
